#!/usr/bin/env python3
"""Generate the eight T09 rendered packs (4 canonical + 4 as-built)
and their byte-level diffs, for Alex's F-B1-2 verification (point 4).
Rendering algorithm identical to verify_transcription.py (Batch 1)
and test_reconciliation.py (reconciliation Test 8)."""
import difflib, hashlib, json, pathlib

SNAP = pathlib.Path("/home/hatch/workspace/nemotron-pilot/freeze/PILOT-CORPUS-SNAPSHOT-01")
DATA = pathlib.Path("/home/hatch/workspace/nemotron-pilot/batch1-2026-11-13")
packs = json.loads((DATA / "PILOT-DATA-PACKS-01.json").read_text())
expected = json.loads((DATA / "PILOT-DATA-EXPECTED-01.json").read_text())
t09 = json.loads((DATA / "PILOT-DATA-T09-01.json").read_text())
fixtures = json.loads((DATA / "PILOT-DATA-FIXTURES-01.json").read_text())
secs = {}
for line in open(SNAP / "sections.jsonl"):
    s = json.loads(line)
    secs[s["section_id"]] = s

def manifest_row(ref):
    body = ref.split(":", 1)[1]
    fname, key = body.split("#")
    doc = {"PILOT-DATA-PACKS-01": packs, "PILOT-DATA-EXPECTED-01": expected,
           "PILOT-DATA-T09-01": t09, "PILOT-DATA-FIXTURES-01": fixtures}[fname]
    if key.startswith("receipt-"):
        return "RECEIPT SUBMITTED FOR CLOSURE:\n" + \
            json.dumps(doc["RECEIPTS"][key[8:]], indent=1)
    if key in ("obligation-spec-text", "obligation-spec"):
        return doc["obligation_spec_text"]
    return doc["fixtures"][key]

def render(tid, canonical):
    parts = []
    for item in packs["trees"][tid]["pack"]:
        if "section" in item:
            s = secs[item["section"]]
            parts.append(f"=== SECTION {s['section_id']} · doc {s['doc']} · "
                         f"{s['heading_path']} · sha256 {s['sha256'][:16]}… "
                         f"===\n{s['text']}")
        else:
            ref = item.get("fixture_ref") or item.get("receipt_ref")
            fid = ref.split("#")[1]
            if canonical and fid == "obligation-spec-text":
                fid = "obligation-spec"
            label = fid if not fid.startswith("receipt-") else "receipt-" + fid[8:]
            parts.append(f"=== FIXTURE {label} ===\n{manifest_row(ref)}")
    return "\n".join(parts)

out = pathlib.Path("/home/hatch/workspace/duenna-letters/fb12-renders")
out.mkdir(exist_ok=True)
lines = []
for tid in ("T09-FR-A", "T09-FR-B", "T09-FR-C", "T09-FR-VALID"):
    can, asb = render(tid, True), render(tid, False)
    (out / f"{tid}.canonical.txt").write_text(can)
    (out / f"{tid}.asbuilt.txt").write_text(asb)
    d = list(difflib.unified_diff(asb.split("\n"), can.split("\n"),
                                  lineterm="", n=1))
    lines.append(f"## {tid}\ncanonical sha256 "
                 f"{hashlib.sha256(can.encode()).hexdigest()}\n"
                 f"as-built  sha256 "
                 f"{hashlib.sha256(asb.encode()).hexdigest()}\n"
                 f"```diff\n" + "\n".join(d) + "\n```\n")
pathlib.Path("/home/hatch/workspace/duenna-letters/F-B1-2-T09-DIFFS.md").write_text(
    "# F-B1-2 — T09 rendered-pack diffs (as-built → canonical)\n\n"
    "Generated by make_fb12_renders.py (rendering identical to the "
    "Batch 1 verifier). Each pair differs ONLY in the fixture header "
    "label line.\n\n" + "\n".join(lines))
print("renders + diffs written")
