#!/bin/bash
# Generate identity_records.h from the installed objects.
# Usage: gen_identity_records.sh <harness-path> <interpreter-path> <out.h>
set -euo pipefail
H=$(realpath "$1"); I=$(realpath "$2"); OUT=$3
read -r hd hi hm <<< "$(stat -c '%d %i %a' "$H")"
read -r id ii im <<< "$(stat -c '%d %i %a' "$I")"
{
echo '/* GENERATED by gen_identity_records.sh — do not edit. */'
echo '#ifndef PILOT_IDENTITY_RECORDS_H'
echo '#define PILOT_IDENTITY_RECORDS_H'
echo "#define INTERPRETER_PATH \"$I\""
echo "#define IDREC_HARNESS_DEV  ${hd}ull"
echo "#define IDREC_HARNESS_INO  ${hi}ull"
echo "#define IDREC_HARNESS_MODE 0${hm}ull"
echo "#define IDREC_INTERP_DEV   ${id}ull"
echo "#define IDREC_INTERP_INO   ${ii}ull"
echo "#define IDREC_INTERP_MODE  0${im}ull"
echo '#endif'
} > "$OUT"
echo "generated $OUT for $H and $I"
