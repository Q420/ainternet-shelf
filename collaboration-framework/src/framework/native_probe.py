def _classify_call(name, parsed):
    """One call's classification. The unoffered fact is
    load-bearing and is never masked by the call's
    argument state: a readable name outside the offered
    set is an unoffered attempt whatever its arguments.
    An offered call whose arguments do not parse to a
    JSON object is malformed — invalid native behaviour,
    never a successful offered call (scope Rev 2), the
    standard the adapter's translation seam applies. An
    unreadable call (no readable name) is malformed."""
    if not isinstance(name, str) or not name:
        return "malformed"
    if name not in OFFERED_TOOLS:
        return "unoffered_tool_attempt"
    if parsed is _probe._UNPARSEABLE or \
            not isinstance(parsed, dict):
        return "malformed"
    return "offered_tool_call"


def _call_record(name, raw_arguments, parsed, source):
    return {
        "name": name,
        "source": source,
        "arguments_raw": raw_arguments,
        "arguments": parsed
        if parsed is not _probe._UNPARSEABLE else None,
        "arguments_parseable":
            parsed is not _probe._UNPARSEABLE,
        "classification": _classify_call(name, parsed),
    }


def _call_records_from_message(message):
    """The per-call records of an accepted completion's
    message, mirroring the probe's readability rules: None
    where the message carries no readable call set (no
    tool_calls, or an empty list). An unreadable call
    entry stands as one malformed record — the response
    did attempt a call; its unreadability is the fact."""
    raw_calls = message.get("tool_calls")
    if not isinstance(raw_calls, list) or not raw_calls:
        return None
    records = []
    for call in raw_calls:
        function = call.get("function") \
            if isinstance(call, dict) else None
        if not isinstance(function, dict) or \
                not isinstance(function.get("name"), str):
            records.append(_call_record(
                None, None, _probe._UNPARSEABLE, "message"))
            continue
        raw_arguments = function.get("arguments")
        records.append(_call_record(
            function["name"], raw_arguments,
            _probe._parse_arguments(raw_arguments),
            "message"))
    return records


def _call_records_from_error_body(error_body):
    """The per-call records attributable from a provider
    error body, through the probe's own attribution (the
    failed-generation object the provider refused to
    deliver): None where no attempt is attributable. The
    raw generation string stands in the retained provider
    body; the record carries the parsed arguments."""
    pairs = _probe._calls_from_error_body(error_body)
    if pairs is None:
        return None
    return [_call_record(name, None, parsed, "error_body")
            for name, parsed in pairs]


def _aggregate(records, text_form):
    """The trial's aggregate classification: content in
    the text channel beside native calls is mixed (both
    channels used); otherwise the calls' classes decide —
    one shared class, or mixed where they differ. Every
    call stands in the record whatever the aggregate
    says, and the unoffered fact rides in the trial's
    flags, so no aggregate can conceal it."""
    if text_form != "none":
        return "mixed"
    classes = [r["classification"] for r in records]
    if all(c == classes[0] for c in classes):
        return classes[0]
    return "mixed"


def classify_native_capture(capture):
    """The classification of one raw capture, on the
    probe's capture protocol: (the result dict) the
    aggregate behaviour, the delivery on its own axis,
    the per-call records, the text channel's form, and
    the flags the decision thresholds read. Delivery and
    behaviour are independent axes, exactly as the
    assembly probe established: an unoffered attempt the
    provider refused is unoffered_tool_attempt ×
    provider_refused, not a clean refusal and not a
    delivered call."""
    body = capture.get("body")
    if isinstance(body, str):
        completion = None
        try:
            completion = json.loads(body)
        except ValueError:
            completion = None
        message = None
        if isinstance(completion, dict):
            try:
                candidate = completion["choices"][0][
                    "message"]
            except (KeyError, IndexError, TypeError):
                candidate = None
            if isinstance(candidate, dict):
                message = candidate
        if message is None:
            return _classification(
                "malformed", "provider_accepted", [],
                "none")
        records = _call_records_from_message(message)
        content = message.get("content")
        text_form = "none"
        if isinstance(content, str) and content.strip():
            obj = _probe._json_object(content)
            text_form = "text_contract" if (
                obj is not None and "outcome" in obj) \
                else "other"
        if records is None:
            behaviour = {
                "text_contract": "text_contract",
                "other": "malformed",
                "none": "no_observable_behaviour",
            }[text_form]
            return _classification(
                behaviour, "provider_accepted", [],
                text_form)
        return _classification(
            _aggregate(records, text_form),
            "provider_accepted", records, text_form)
    error_body = capture.get("error_body")
    if isinstance(error_body, str):
        records = _call_records_from_error_body(error_body)
        if records is not None:
            return _classification(
                _aggregate(records, "none"),
                "provider_refused", records, "none")
        return _classification(
            "no_observable_behaviour", "provider_failed",
            [], "none")
    if capture.get("http_status") is not None or \
            capture.get("diagnostics"):
        return _classification(
            "no_observable_behaviour", "provider_failed",
            [], "none")
    return _classification(
        "no_observable_behaviour", "indeterminate", [],
        "none")


def _classification(behaviour, delivery, records,
                    text_form):
    return {
        "behaviour": behaviour,
        "delivery": delivery,
        "calls": records,
        "text_form": text_form,
        "has_offered_call": any(
            r["classification"] == "offered_tool_call"
            for r in records),
        "has_unoffered_call": any(
            r["classification"] == "unoffered_tool_attempt"
            for r in records),
        "has_malformed_call": any(
            r["classification"] == "malformed"
            for r in records),
    }


