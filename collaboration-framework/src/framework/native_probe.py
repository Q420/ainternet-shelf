def trial_evidence(index, capture):
    """One trial's recorded evidence: the classification
    (aggregate and per call), the settled flag — settled
    is evidence-complete, per this scope's definition —
    and the retained provider body and diagnostics under
    the capture ceiling, each with its hash, on the
    assembly probe's retention discipline: the raw
    provider response retained whole, the decoded
    envelope derivable from it, the full assistant
    message and every call preserved in the body as
    received."""
    result = classify_native_capture(capture)
    body_text = capture.get("body")
    if not isinstance(body_text, str):
        body_text = capture.get("error_body")
    if not isinstance(body_text, str):
        body_text = None
    diag_text = capture.get("diagnostics")
    if not isinstance(diag_text, str):
        diag_text = None
    body_raw = body_text.encode("utf-8") \
        if body_text is not None else b""
    diag_budget = max(0, CAPTURE_CEILING - len(body_raw))
    if diag_text is not None:
        retained_diag, diag_complete = _probe._retain(
            diag_text, diag_budget)
    else:
        retained_diag, diag_complete = None, True
    if body_text is not None:
        retained_body, body_complete = _probe._retain(
            body_text, CAPTURE_CEILING)
    else:
        retained_body, body_complete = None, False
    body_bytes = len(retained_body.encode("utf-8")) \
        if retained_body is not None else 0
    diag_bytes = len(retained_diag.encode("utf-8")) \
        if retained_diag is not None else 0
    metadata = capture.get("metadata")
    if not isinstance(metadata, dict):
        metadata = {}
    status = capture.get("http_status")
    if not isinstance(status, int) or \
            isinstance(status, bool):
        status = None
    return {
        "trial": index,
        "behaviour": result["behaviour"],
        "delivery": result["delivery"],
        "calls": result["calls"],
        "text_form": result["text_form"],
        "has_offered_call": result["has_offered_call"],
        "has_unoffered_call": result["has_unoffered_call"],
        "has_malformed_call": result["has_malformed_call"],
        "settled": body_complete,
        "provider_body": retained_body,
        "provider_body_bytes": body_bytes,
        "provider_body_sha256": _sha256(
            retained_body.encode("utf-8"))
            if retained_body is not None else None,
        "provider_body_complete": body_complete,
        "http_status": status,
        "metadata": metadata,
        "metadata_sha256": sha256_hex(canonical(metadata)),
        "diagnostics": retained_diag,
        "diagnostics_bytes": diag_bytes,
        "diagnostics_sha256": _sha256(
            retained_diag.encode("utf-8"))
            if retained_diag is not None else None,
        "diagnostics_complete": diag_complete,
        "aggregate_bytes": body_bytes + diag_bytes,
        "evidence_complete": body_complete,
    }


def summarise_native(trials):
    """(counts, settled_count, reading): the counts over
    both dimensions exactly as recorded, and the scope's
    decision thresholds, stated in advance as witnesses:
    three or more aggregate offered_tool_call trials
    supports the locked-door hypothesis; three or more
    trials carrying an unoffered call strengthens the
    deeper-habit hypothesis; anything else is a split /
    inconclusive result, reported as exactly that. Five
    trials establish what happened in five trials."""
    counts = {
        "behaviour": {name: 0 for name in BEHAVIOURS},
        "delivery": {name: 0 for name in DELIVERIES},
    }
    for trial in trials:
        if trial.get("behaviour") in counts["behaviour"]:
            counts["behaviour"][trial["behaviour"]] += 1
        if trial.get("delivery") in counts["delivery"]:
            counts["delivery"][trial["delivery"]] += 1
    settled = sum(1 for trial in trials
                  if trial.get("settled"))
    offered = counts["behaviour"]["offered_tool_call"]
    unoffered_carriers = sum(
        1 for trial in trials
        if trial.get("has_unoffered_call"))
    if offered >= 3:
        reading = "locked_door_supported"
    elif unoffered_carriers >= 3:
        reading = "deeper_habit_strengthened"
    else:
        reading = "split_inconclusive"
    return counts, settled, reading


def run_native_trials(raw_call, baseline, modified,
                      comparison):
    """The bounded trial run: the precondition verified
    first — a failure refuses before any provider
    request — then exactly TRIAL_COUNT trials, each ONE
    generation request through the injected raw-call
    callable, each ending at its first response. No
    follow-up request, no dispatch, no execution, no
    tool-result response, ever: the raw call is the
    probe's capture protocol, which returns what the
    provider sent and interprets nothing. A raw call that
    raises, or returns no capture, is itself evidence — a
    delivery failure with the failure as its diagnostic —
    never a runner exception."""
    problems = check_precondition(
        baseline, modified, comparison)
    if problems:
        raise NativeProbeRefusal(
            "the request comparison fails the scope's "
            "precondition; no trial runs: "
            + "; ".join(problems))
    trials = []
    for index in range(1, TRIAL_COUNT + 1):
        request = copy.deepcopy(modified)
        try:
            capture = raw_call(request)
            if not isinstance(capture, dict):
                capture = {
                    "diagnostics": "the raw call returned "
                                   "no capture object"}
        except Exception as exc:  # the capture IS the
            # failure, as in the assembly probe's runner
            capture = {
                "diagnostics": f"{type(exc).__name__}: {exc}"}
        trials.append(trial_evidence(index, capture))
    return trials


