# The comparison artifact and its precondition.
# ----------------------------------------------------------------

_ABSENT = object()


def _diff_into(path, a, b, out):
    """The recursive field-by-field walk: a differing
    leaf (or a value present on one side only) records
    one entry at its path, with each side's presence and
    canonical hash. Equal subtrees record nothing."""
    if a is not _ABSENT and b is not _ABSENT:
        if canonical(a) == canonical(b):
            return
        if isinstance(a, dict) and isinstance(b, dict):
            for key in sorted(set(a) | set(b)):
                _diff_into(
                    f"{path}.{key}" if path else key,
                    a.get(key, _ABSENT),
                    b.get(key, _ABSENT), out)
            return
        if isinstance(a, list) and isinstance(b, list) \
                and len(a) == len(b):
            for i in range(len(a)):
                _diff_into(f"{path}[{i}]", a[i], b[i], out)
            return
    entry = {"path": path}
    for label, value in (("baseline", a),
                         ("modified", b)):
        if value is _ABSENT:
            entry[label] = {"present": False,
                            "sha256": None}
        else:
            entry[label] = {
                "present": True,
                "sha256": sha256_hex(canonical(value))}
    out.append(entry)


def diff_requests(baseline, modified):
    """The machine-readable comparison: every differing
    path between the two requests, each with both sides'
    presence and canonical hashes. An empty list means
    the requests are canonically identical."""
    out = []
    _diff_into("", baseline, modified, out)
    return sorted(out, key=lambda e: e["path"])


def _top_segment(path):
    return path.split(".")[0].split("[")[0]


def build_comparison(baseline, modified, definitions,
                     catalogue_source, baseline_info):
    """The comparison artifact (scope Rev 2): both
    requests identified by canonical hash, the
    definitions by theirs, the catalogue source, the
    tool-choice setting as actually sent on both sides,
    and the full field-by-field diff."""
    diff = diff_requests(baseline, modified)
    return {
        "kind": "native-offer probe request comparison "
                "(NATIVE-OFFER-PROBE-SCOPE Rev 2)",
        "baseline_sha256": sha256_hex(canonical(baseline)),
        "modified_sha256": sha256_hex(canonical(modified)),
        "definitions_sha256": sha256_hex(
            canonical(definitions)),
        "catalogue_source": catalogue_source,
        "baseline_construction": baseline_info,
        "tool_choice": {
            "baseline": (
                "absent — no tool_choice field stands in "
                "the request; with no tools offered, the "
                "provider names this configuration tool "
                "choice none"),
            "modified": (
                "absent — the field is omitted, leaving "
                "the provider's natural (automatic) tool "
                "choice"),
        },
        "allowed_top_level_paths": list(ALLOWED_DIFF_PATHS),
        "differing_paths": [e["path"] for e in diff],
        "diff": diff,
    }


def check_precondition(baseline, modified, comparison):
    """The scope's precondition, checked — never
    asserted: the comparison must be a comparison OF
    THESE requests (its hashes recompute), its recorded
    diff must equal the recomputed diff in full — every
    entry, both sides' presence and canonical hashes —
    its recorded definitions hash must equal the
    canonical hash of the modified request's actual
    tools field, its recorded catalogue source hash
    must agree with the baseline construction's
    catalogue commitment, every differing path must sit
    under an allowed tool-presentation field, and the
    intervention must actually be present (the tools
    field must differ). Returns the list of problems;
    empty is a pass."""
    problems = []
    if comparison.get("baseline_sha256") != \
            sha256_hex(canonical(baseline)):
        problems.append(
            "the comparison's baseline hash does not "
            "recompute from the baseline request")
    if comparison.get("modified_sha256") != \
            sha256_hex(canonical(modified)):
        problems.append(
            "the comparison's modified hash does not "
            "recompute from the modified request")
    diff = diff_requests(baseline, modified)
    if [e["path"] for e in diff] != \
            comparison.get("differing_paths"):
        problems.append(
            "the comparison's recorded diff is not the "
            "recomputed diff of these requests")
    if comparison.get("diff") != diff:
        problems.append(
            "the comparison's recorded diff entries do "
            "not equal the recomputed diff in full — "
            "every path, and both sides' presence and "
            "canonical hashes")
    if comparison.get("definitions_sha256") != \
            sha256_hex(canonical(modified.get("tools"))):
        problems.append(
            "the comparison's recorded definitions hash "
            "does not equal the canonical hash of the "
            "modified request's actual tools field")
    catalogue_source = comparison.get("catalogue_source")
    if not isinstance(catalogue_source, dict):
        catalogue_source = {}
    construction = comparison.get("baseline_construction")
    if not isinstance(construction, dict):
        construction = {}
    if not catalogue_source.get("catalogue_hash") or \
            catalogue_source.get("catalogue_hash") != \
            construction.get("catalogue_hash"):
        problems.append(
            "the comparison's recorded catalogue source "
            "hash does not agree with the baseline "
            "construction's catalogue commitment")
    tops = {_top_segment(e["path"]) for e in diff}
    for top in sorted(tops):
        if top not in ALLOWED_DIFF_PATHS:
            problems.append(
                f"the requests differ under {top!r}, "
                f"outside the tool-presentation paths "
                f"{list(ALLOWED_DIFF_PATHS)}")
    if "tools" not in tops:
        problems.append(
            "the intervention is absent: the requests do "
            "not differ in the tools field")
    return problems


