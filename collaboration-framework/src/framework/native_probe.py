"""The native-offer probe (NATIVE-OFFER-PROBE-SCOPE
Rev 2, PASSED at INDEX 334): a bounded, observational
experiment that asks one question in the worker's real
task context — when the worker's granted actions are
offered as real native tools, what is its first action?

The evidenced run (INDEX 329/330) established the
environment-tool reach under text mode: no tools offered,
and the provider's refusal named the configuration "tool
choice is none". It did not establish how the model
behaves when its actual granted actions are presented
through its native tool interface. This probe isolates
that one variable — the request construction — holding
everything else constant:

- the baseline request is the evidenced assembly's
  iteration-1 worker request, regenerated by the real
  construction path (see build_baseline);
- the modified request is derived from that exact object
  with exactly the tool-presentation intervention: the
  three granted retrieval actions offered as native tool
  definitions, and no tool_choice field sent (the field
  omitted — the provider's natural setting);
- a machine-readable comparison of the two requests is a
  precondition, not an assertion: any differing path
  beyond the tool-presentation paths refuses the probe
  before any trial runs.

Observation only, in the assembly probe's posture: the
offered definitions are experimental input, not grants.
Exactly one provider generation request is made per
trial; a tool call is captured and the trial ends —
nothing is dispatched, executed, answered, or followed
by a second request. Classification preserves both the
per-call classifications and the aggregate trial
classification, with provider delivery recorded as a
separate dimension, so the decision thresholds (scope
Rev 2) are independently reconstructable from the
evidence rather than resting on a summary label.

The baseline is a REPRODUCIBLE REPRESENTATION, in the
scope's own terms, and the representation is exact
about its one substitution. The iteration-1 package is
rebuilt by the loop's own package construction from the
evidenced record truncated at the activation event —
the record state the loop itself opened on — and the
regeneration is verified against the record's own
commitments (the LOOP_ITERATION event's cursor range,
catalogue hash and registry version must reproduce
exactly, or the build refuses). Every field of the
package is thereby record-determined except one:
bounds.seconds_remaining, a live countdown read from
the doorway's monotonic anchor at construction time,
whose original value no artifact records. The
regeneration stands the doorway's clock at the stored
activation anchor while the real derivation runs, so
the field carries the full pinned deadline — the value
at the activation instant. The request that is hashed,
compared and (at the released run) sent is the request
this construction produces, with that one field's
provenance stated here and in the comparison artifact.
"""

