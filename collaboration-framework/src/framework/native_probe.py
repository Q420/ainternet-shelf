_TRIAL_HASH_FIELDS = (
    "trial", "request_started_wall_at",
    "request_start_monotonic_offset_seconds",
    "pacing_wait_phase_seconds",
    "behaviour", "delivery", "text_form",
    "has_offered_call", "has_unoffered_call",
    "has_malformed_call", "settled", "http_status",
    "provider_body_sha256", "provider_body_bytes",
    "provider_body_complete", "metadata_sha256",
    "diagnostics_sha256", "diagnostics_bytes",
    "diagnostics_complete", "aggregate_bytes",
    "evidence_complete",
)


def _evidence_projection(evidence):
    """The evidence-bearing projection the evidence hash
    binds: the comparison's hashes, the per-trial
    classifications — aggregate AND per call, each call's
    name, classification and arguments hash, so the
    thresholds are reconstructable from the hash-bound
    projection alone — the counts and the reading."""
    trials = []
    for trial in evidence.get("trials") or []:
        entry = {key: trial.get(key)
                 for key in _TRIAL_HASH_FIELDS}
        entry["calls"] = [{
            "name": call.get("name"),
            "classification": call.get("classification"),
            "arguments_sha256": sha256_hex(canonical(
                call.get("arguments")))
            if call.get("arguments") is not None else None,
            "arguments_parseable":
                call.get("arguments_parseable"),
        } for call in trial.get("calls") or []]
        trials.append(entry)
    return {
        "baseline_sha256": evidence.get("baseline_sha256"),
        "modified_sha256": evidence.get("modified_sha256"),
        "definitions_sha256": evidence.get(
            "definitions_sha256"),
        "comparison_sha256": evidence.get(
            "comparison_sha256"),
        "trials": trials,
        "counts": evidence.get("counts"),
        "settled_count": evidence.get("settled_count"),
        "reading": evidence.get("reading"),
    }


def native_evidence_hash(evidence):
    """The hash over the evidence artifact's own
    projection — the binding that ties any later
    judgement of this probe to this exact evidence."""
    return sha256_hex(canonical(
        _evidence_projection(evidence)))


def probe_evidence_object(comparison, trials):
    """The probe's evidence artifact: the comparison
    referenced by its hash (the artifact itself stands
    as its own durable file), the per-trial evidence,
    the counts, and the reading the thresholds produce —
    with the evidence hash computed over the artifact's
    projection."""
    counts, settled, reading = summarise_native(trials)
    evidence = {
        "kind": "native-offer probe evidence "
                "(NATIVE-OFFER-PROBE-SCOPE Rev 2)",
        "comparison_sha256": sha256_hex(
            canonical(comparison)),
        "baseline_sha256": comparison["baseline_sha256"],
        "modified_sha256": comparison["modified_sha256"],
        "definitions_sha256":
            comparison["definitions_sha256"],
        "trial_count": len(trials),
        "trials": trials,
        "counts": counts,
        "settled_count": settled,
        "reading": reading,
    }
    evidence["evidence_hash"] = native_evidence_hash(
        evidence)
    return evidence


def write_outputs(out_dir, comparison, evidence=None):
    """The probe's durable outputs: the comparison
    artifact as its own file (comparison.json), and the
    evidence artifact (probe-evidence.json) where a trial
    run produced one. Both written as canonical JSON.
    Returns the paths written."""
    os.makedirs(out_dir, exist_ok=True)
    written = []
    comparison_path = os.path.join(
        out_dir, "comparison.json")
    with open(comparison_path, "wb") as fh:
        fh.write(canonical(comparison))
    written.append(comparison_path)
    if evidence is not None:
        evidence_path = os.path.join(
            out_dir, "probe-evidence.json")
        with open(evidence_path, "wb") as fh:
            fh.write(canonical(evidence))
        written.append(evidence_path)
    return written
