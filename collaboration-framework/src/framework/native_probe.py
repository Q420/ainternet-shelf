def trial_evidence(index, capture,
                   request_started_wall_at=None,
                   request_start_monotonic_offset_seconds=None,
                   pacing_wait_phase_seconds=0.0):
    """One trial's recorded evidence: the classification
    (aggregate and per call), the settled flag — settled
    is evidence-complete, per this scope's definition —
    the trial's pacing record, in two distinguished
    parts: request_started_wall_at, the request's start
    on the WALL clock, recorded for human-readable
    chronology only and never a pacing measurement;
    and request_start_monotonic_offset_seconds, the
    request's start on the MONOTONIC clock expressed
    as seconds since the run's first request start —
    the start stamped at the call boundary, after
    request preparation, immediately before the raw
    call is invoked — together with
    pacing_wait_phase_seconds: the monotonic elapsed
    interval from the beginning of the trial's wait
    phase (which begins after preparation) to that
    call-boundary stamp, which is the time the wait
    phase actually occupied on the monotonic clock,
    including re-measurement between sleeps — not
    necessarily time spent inside the sleeper alone,
    and excluding both preparation and generation
    time. The paced repetition's spacing is
    reconstructable from the monotonic offsets alone,
    and they are bound into the evidence hash — and
    the retained provider body
    and diagnostics under
    the capture ceiling, each with its hash, on the
    assembly probe's retention discipline: the raw
    provider response retained whole, the decoded
    envelope derivable from it, the full assistant
    message and every call preserved in the body as
    received."""
    result = classify_native_capture(capture)
    body_text = capture.get("body")
    if not isinstance(body_text, str):
        body_text = capture.get("error_body")
    if not isinstance(body_text, str):
        body_text = None
    diag_text = capture.get("diagnostics")
    if not isinstance(diag_text, str):
        diag_text = None
    body_raw = body_text.encode("utf-8") \
        if body_text is not None else b""
    diag_budget = max(0, CAPTURE_CEILING - len(body_raw))
    if diag_text is not None:
        retained_diag, diag_complete = _probe._retain(
            diag_text, diag_budget)
    else:
        retained_diag, diag_complete = None, True
    if body_text is not None:
        retained_body, body_complete = _probe._retain(
            body_text, CAPTURE_CEILING)
    else:
        retained_body, body_complete = None, False
    body_bytes = len(retained_body.encode("utf-8")) \
        if retained_body is not None else 0
    diag_bytes = len(retained_diag.encode("utf-8")) \
        if retained_diag is not None else 0
    metadata = capture.get("metadata")
    if not isinstance(metadata, dict):
        metadata = {}
    status = capture.get("http_status")
    if not isinstance(status, int) or \
            isinstance(status, bool):
        status = None
    return {
        "trial": index,
        "request_started_wall_at": request_started_wall_at,
        "request_start_monotonic_offset_seconds":
            request_start_monotonic_offset_seconds,
        "pacing_wait_phase_seconds":
            pacing_wait_phase_seconds,
        "behaviour": result["behaviour"],
        "delivery": result["delivery"],
        "calls": result["calls"],
        "text_form": result["text_form"],
        "has_offered_call": result["has_offered_call"],
        "has_unoffered_call": result["has_unoffered_call"],
        "has_malformed_call": result["has_malformed_call"],
        "settled": body_complete,
        "provider_body": retained_body,
        "provider_body_bytes": body_bytes,
        "provider_body_sha256": _sha256(
            retained_body.encode("utf-8"))
            if retained_body is not None else None,
        "provider_body_complete": body_complete,
        "http_status": status,
        "metadata": metadata,
        "metadata_sha256": sha256_hex(canonical(metadata)),
        "diagnostics": retained_diag,
        "diagnostics_bytes": diag_bytes,
        "diagnostics_sha256": _sha256(
            retained_diag.encode("utf-8"))
            if retained_diag is not None else None,
        "diagnostics_complete": diag_complete,
        "aggregate_bytes": body_bytes + diag_bytes,
        "evidence_complete": body_complete,
    }


def summarise_native(trials):
    """(counts, settled_count, reading): the counts over
    both dimensions exactly as recorded, and the scope's
    decision thresholds, stated in advance as witnesses:
    three or more aggregate offered_tool_call trials
    supports the locked-door hypothesis; three or more
    trials carrying an unoffered call strengthens the
    deeper-habit hypothesis; anything else is a split /
    inconclusive result, reported as exactly that. Five
    trials establish what happened in five trials."""
    counts = {
        "behaviour": {name: 0 for name in BEHAVIOURS},
        "delivery": {name: 0 for name in DELIVERIES},
    }
    for trial in trials:
        if trial.get("behaviour") in counts["behaviour"]:
            counts["behaviour"][trial["behaviour"]] += 1
        if trial.get("delivery") in counts["delivery"]:
            counts["delivery"][trial["delivery"]] += 1
    settled = sum(1 for trial in trials
                  if trial.get("settled"))
    offered = counts["behaviour"]["offered_tool_call"]
    unoffered_carriers = sum(
        1 for trial in trials
        if trial.get("has_unoffered_call"))
    if offered >= 3:
        reading = "locked_door_supported"
    elif unoffered_carriers >= 3:
        reading = "deeper_habit_strengthened"
    else:
        reading = "split_inconclusive"
    return counts, settled, reading


def _prepare_request(modified):
    """The runner's request-preparation step: a deep
    copy of the admitted modified request, so a trial's
    invocation can never mutate the standing request
    the comparison describes. Preparation runs BEFORE
    the trial's wait phase (INDEX 347), so its cost —
    however it varies from trial to trial — sits
    outside both the enforced start interval and the
    recorded wait, and the interval is measured purely
    between call-boundary stamps."""
    return copy.deepcopy(modified)


def run_native_trials(raw_call, baseline, modified,
                      comparison, clock=None,
                      sleeper=None, monotonic_clock=None,
                      wall_clock=None):
    """The bounded trial run: the precondition verified
    first — a failure refuses before any provider
    request, and before any pacing wait — then exactly
    TRIAL_COUNT trials, each ONE generation request
    through the injected raw-call callable, each ending
    at its first response. No follow-up request, no
    dispatch, no execution, no tool-result response,
    ever: the raw call is the probe's capture protocol,
    which returns what the provider sent and interprets
    nothing. A raw call that raises, or returns no
    capture, is itself evidence — a delivery failure
    with the failure as its diagnostic — never a runner
    exception.

    The trials are PACED (the paced repetition, INDEX
    340): strictly sequential, each request starting at
    least MIN_TRIAL_START_INTERVAL_SECONDS after the
    previous request's start. The wait before a trial
    is the shortfall between the floor and the time
    already elapsed since the previous start — sleeping
    only that shortfall — so a generation that itself
    takes time leaves a correspondingly shorter wait,
    and one longer than the floor leaves none. The
    first trial starts immediately.

    The enforced interval runs between CALL-BOUNDARY
    starts (INDEX 347). Each trial is sequenced:
    prepare the request first; then the wait phase,
    which waits the shortfall measured from the
    previous trial's call-boundary start; then stamp
    the monotonic start immediately before invoking
    the raw call — the closest practical measurement
    of entry into the raw-call seam — and invoke. The
    recorded start offsets are therefore the invocation
    starts themselves, and preparation overhead,
    however it varies between trials, is inside the
    interval budget (it consumes elapsed time the
    wait then tops up) but can never compress the
    actual spacing between invocations below the
    floor: the wait is not measured until preparation
    is complete, and nothing but the invocation
    follows the stamp.

    The pacing rests on a MONOTONIC clock end to end
    (INDEX 342): elapsed time, the start spacing and
    the recorded start offsets are all monotonic
    measurements (time.monotonic by default), and
    after every sleep the elapsed time is re-measured
    — a sleeper that returns early leaves the runner
    waiting again until the interval has actually
    elapsed, never proceeding on a wait that merely
    was requested. The wall clock (time.time by
    default) is read once per trial, immediately
    before the monotonic stamp, for chronology
    only, recorded under its own field, and never
    enters the pacing calculation: a wall-clock jump,
    forward or backward, cannot shorten or stretch
    the enforced interval. The wall clock is read
    once per trial immediately BEFORE the monotonic
    stamp, so the stamp — not the chronology read —
    is the final operation before the invocation
    (INDEX 349). Each trial records its
    wall-clock start, its monotonic start offset from
    the run's first request start, and
    pacing_wait_phase_seconds — the monotonic elapsed
    interval from the beginning of its wait phase
    (after preparation) to its call-boundary stamp:
    the time the wait phase actually occupied,
    including re-measurement between sleeps, not
    necessarily time inside the sleeper alone. The
    clocks and sleeper are injectable seams so the
    pacing is witnessable without real waiting; the
    legacy `clock` seam, where a caller supplies it,
    serves as both clocks (single-clock witnesses of
    the pacing arithmetic), while the production
    defaults are the dual clocks above."""
    problems = check_precondition(
        baseline, modified, comparison)
    if problems:
        raise NativeProbeRefusal(
            "the request comparison fails the scope's "
            "precondition; no trial runs: "
            + "; ".join(problems))
    if monotonic_clock is None:
        monotonic_clock = clock if clock is not None \
            else time.monotonic
    if wall_clock is None:
        wall_clock = clock if clock is not None \
            else time.time
    if sleeper is None:
        sleeper = time.sleep
    trials = []
    first_boundary_start = None
    previous_boundary_start = None
    for index in range(1, TRIAL_COUNT + 1):
        # Prepare first (INDEX 347): the request is
        # built before the wait phase, so preparation
        # overhead — however it varies — is elapsed
        # time inside the interval budget, never time
        # hidden between the start stamp and the
        # invocation.
        request = _prepare_request(modified)
        wait = 0.0
        wait_began = None
        if previous_boundary_start is not None:
            wait_began = monotonic_clock()
            while True:
                shortfall = \
                    MIN_TRIAL_START_INTERVAL_SECONDS \
                    - (monotonic_clock()
                       - previous_boundary_start)
                if shortfall <= 0:
                    break
                sleeper(shortfall)
        # The wall clock is read for chronology BEFORE
        # the monotonic stamp (INDEX 349): the stamp is
        # the final operation before the invocation, so
        # the recorded start is immediately before the
        # call itself — not immediately before a
        # chronology read. The wall value never enters
        # the pacing calculation.
        wall_start = wall_clock()
        boundary_start = monotonic_clock()
        if wait_began is not None:
            wait = boundary_start - wait_began
        if first_boundary_start is None:
            first_boundary_start = boundary_start
        previous_boundary_start = boundary_start
        try:
            capture = raw_call(request)
            if not isinstance(capture, dict):
                capture = {
                    "diagnostics": "the raw call returned "
                                   "no capture object"}
        except Exception as exc:  # the capture IS the
            # failure, as in the assembly probe's runner
            capture = {
                "diagnostics": f"{type(exc).__name__}: {exc}"}
        trials.append(trial_evidence(
            index, capture,
            request_started_wall_at=wall_start,
            request_start_monotonic_offset_seconds=(
                boundary_start - first_boundary_start),
            pacing_wait_phase_seconds=wait))
    return trials


