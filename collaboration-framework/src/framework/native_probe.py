def derive_offered_definitions(package, catalogue_hash):
    """The native definitions for exactly the offered
    tools, derived from the sealed catalogue: the
    package's catalogue entries for the three offered
    tools, passed through the adapter's own native
    derivation (the same per-grant derivation native
    mode offers by) — name, description and parameters
    are the catalogue's own; nothing is invented, renamed
    or supplemented. Returns (definitions,
    catalogue_source): the source record the comparison
    artifact carries, naming where the definitions came
    from and the catalogue's hash."""
    entries = [entry for entry in package.get("tools")
               or [] if isinstance(entry, dict)
               and entry.get("tool") in OFFERED_TOOLS]
    definitions = \
        OpenAICompatibleAdapter._native_tool_definitions(
            {"tools": entries})
    names = [d["function"]["name"] for d in definitions]
    if names != list(OFFERED_TOOLS):
        raise NativeProbeRefusal(
            f"the catalogue derivation yields {names}, "
            f"not the offered tools {list(OFFERED_TOOLS)};"
            f" the intervention cannot be constructed "
            f"from this catalogue")
    catalogue_source = {
        "catalogue": (
            "the worker-facing tool catalogue the loop "
            "derives from the sealed ASSEMBLY_GENERATED "
            "grants (framework.loop._derive_catalogue), "
            "as carried in the regenerated package's "
            "tools field"),
        "catalogue_hash": catalogue_hash,
        "derivation": (
            "framework.adapter.OpenAICompatibleAdapter."
            "_native_tool_definitions over the catalogue "
            "entries for the offered tools — the "
            "adapter's own per-grant native derivation"),
        "offered_tools": list(OFFERED_TOOLS),
    }
    return definitions, catalogue_source


def build_modified_request(baseline, definitions):
    """The modified request: the baseline object with the
    tool-presentation intervention applied — the native
    definitions added as its tools field, and no
    tool_choice field (omitted, leaving the provider's
    natural setting; the baseline sends none either).
    Derived from the baseline object itself, never
    rebuilt, so the comparison's premise — everything
    else identical — holds by construction and is then
    verified by the diff."""
    modified = copy.deepcopy(baseline)
    modified["tools"] = copy.deepcopy(definitions)
    modified.pop("tool_choice", None)
    return modified


