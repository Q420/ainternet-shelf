def _read_source_record(source_run_dir):
    """The source run's events, read through a read-only
    connection: the evidenced record is evidence, and
    this build never opens it for writing. Returns the
    event list in the store's own shape."""
    db_path = os.path.join(source_run_dir, "run.db")
    conn = sqlite3.connect(f"file:{db_path}?mode=ro",
                           uri=True)
    try:
        rows = conn.execute(
            "SELECT event_seq, event_id, run_id, type, "
            "actor, affected, payload, ts, prev_hash, hash "
            "FROM events ORDER BY event_seq").fetchall()
    finally:
        conn.close()
    events = []
    for seq, eid, run_id, typ, actor, affected, payload, \
            ts, prev, h in rows:
        events.append({
            "event_seq": seq, "event_id": eid,
            "run_id": run_id, "type": typ, "actor": actor,
            "affected": json.loads(affected),
            "payload": json.loads(payload), "ts": ts,
            "prev_hash": prev, "hash": h})
    return events


def _truncated_store_copy(source_run_dir, work_dir,
                          through_seq):
    """A copy of the source store holding exactly the
    events through `through_seq` — the record as it stood
    at that event — built by a raw backup and a tail cut
    on the COPY (the store's append-only triggers are
    dropped on the copy only; the source is never
    touched). The prefix hash chain stands verbatim, as
    recorded. The doorway's anchors file is copied beside
    it, as the doorway expects. Returns the copy's path."""
    os.makedirs(work_dir, exist_ok=True)
    dest = os.path.join(work_dir, "run.db")
    src = sqlite3.connect(
        f"file:{os.path.join(source_run_dir, 'run.db')}"
        f"?mode=ro", uri=True)
    dst = sqlite3.connect(dest)
    try:
        src.backup(dst)
        dst.execute(
            "DROP TRIGGER IF EXISTS events_no_delete")
        dst.execute(
            "DELETE FROM events WHERE event_seq > ?",
            (through_seq,))
        dst.commit()
    finally:
        dst.close()
        src.close()
    anchors = os.path.join(source_run_dir,
                           "run.db.anchors.json")
    if os.path.exists(anchors):
        shutil.copyfile(anchors, dest + ".anchors.json")
    return dest


def build_baseline(source_run_dir, work_dir, model):
    """Regenerate the evidenced assembly's iteration-1
    worker request by the construction path that produced
    it, and verify the regeneration against the record.

    The path, step for step: the source record's first
    LOOP_ITERATION event names the activation and the
    iteration's commitments; the record is copied,
    truncated at the activation event; a doorway over the
    copy folds that state; the loop's context is resolved
    by the same derivations its _open_context performs;
    and the loop's own _build_package constructs the
    package — with the doorway's clock standing at the
    stored activation anchor, so the one live field (the
    bounds' seconds remaining) carries the full pinned
    deadline, the value at the activation instant (see
    this module's docstring for the representation's
    exact terms). The prompt is the adapter's own
    rendering of that package; the messages are the wake
    call's; the request object is the Groq transport's
    construction ({"model", "messages", "temperature":
    0.2} — in text mode nothing is staged, so no tools
    and no tool_choice field stand in it).

    The regeneration REFUSES (NativeProbeRefusal) unless
    the record's own commitments reproduce: the package
    head is the activation event, the cursor range is
    the LOOP_ITERATION event's, and the catalogue hash
    and registry version the loop derives equal the ones
    that event recorded. Returns (request, package,
    info) — info carries the construction's provenance
    for the comparison artifact."""
    events = _read_source_record(source_run_dir)
    iteration_one = None
    for ev in events:
        if ev["type"] == "LOOP_ITERATION" and \
                (ev["payload"] or {}).get("iteration") == 1:
            iteration_one = ev["payload"]
            break
    if iteration_one is None:
        raise NativeProbeRefusal(
            "the source record carries no iteration-1 "
            "LOOP_ITERATION event; there is no evidenced "
            "first request to regenerate")
    assembly_id = iteration_one["assembly_id"]
    instance_id = iteration_one["instance_id"]
    activated_seq = iteration_one["activated_seq"]

    copy_path = _truncated_store_copy(
        source_run_dir, work_dir, activated_seq)
    store = FrameworkStore(copy_path)
    doorway = Doorway(store)
    state = doorway.state()
    _, entry = doorway._assembly_entry_of_instance(
        state, instance_id)
    if entry is None or \
            entry.get("activated_seq") != activated_seq:
        raise NativeProbeRefusal(
            "the truncated record does not resolve the "
            "evidenced activation; the regeneration has "
            "no standing")
    # The loop's context, resolved by the same
    # derivations _open_context performs over this state.
    generated = doorway._generated_payload(assembly_id)
    adapter_mode = None
    if doorway._probe_governed(generated):
        packed = doorway._event_at(entry.get("packed_seq"))
        adapter_mode = (packed or {}).get(
            "payload", {}).get("adapter_mode")
    ctx = {
        "instance_id": instance_id,
        "assembly_id": assembly_id,
        "adapter_mode": adapter_mode,
        "seat": entry.get("seat"),
        "role": (state["seats"].get(entry.get("seat"))
                 or {}).get("role"),
        "case_id": entry.get("case_id"),
        "case_version": entry.get("case_version"),
        "content": copy.deepcopy(
            doorway._pinned_case_content(state, entry)),
        "activated_seq": activated_seq,
        "bounds": doorway._pinned_loop_bounds(state, entry),
        "cursor": state["head_seq"],
        "iterations": 0,
        "recorded": [], "refused": [], "dispatched": [],
        "call_timings": [],
    }
    anchors = doorway._read_anchors()
    anchor_rec = anchors.get(str(activated_seq)) or {}
    anchor = anchor_rec.get("anchor")
    if not isinstance(anchor, (int, float)):
        raise NativeProbeRefusal(
            "the doorway holds no activation anchor for "
            "the evidenced activation; the package's "
            "deadline derivation cannot be reproduced")
    loop = Loop(doorway, None, None)
    real_monotonic = time.monotonic
    time.monotonic = lambda: anchor  # noqa: E731 — the
    # clock stands at the activation instant for the one
    # derivation that reads it (see the module docstring)
    try:
        package, head = loop._build_package(ctx)
    finally:
        time.monotonic = real_monotonic
    problems = []
    if head != activated_seq:
        problems.append(
            f"the package head is {head}, not the "
            f"activation event {activated_seq}")
    if iteration_one.get("cursor_from") != ctx["cursor"] \
            or iteration_one.get("cursor_to") != head:
        problems.append(
            "the cursor range does not reproduce the "
            "LOOP_ITERATION event's recorded range")
    if ctx.get("catalogue_hash") != \
            iteration_one.get("catalogue_hash"):
        problems.append(
            "the derived catalogue hash does not equal "
            "the catalogue hash the LOOP_ITERATION event "
            "recorded")
    if ctx.get("registry_version") != \
            iteration_one.get("registry_version"):
        problems.append(
            "the derived registry version does not equal "
            "the one the LOOP_ITERATION event recorded")
    if problems:
        raise NativeProbeRefusal(
            "the regeneration does not reproduce the "
            "record: " + "; ".join(problems))
    prompt = _render_prompt(package)
    request = {
        "model": model,
        "messages": [
            {"role": "system", "content": _SYSTEM_TEXT},
            {"role": "user", "content": prompt}],
        "temperature": 0.2,
    }
    info = {
        "source_run_dir": source_run_dir,
        "assembly_id": assembly_id,
        "instance_id": instance_id,
        "activated_seq": activated_seq,
        "record_head_at_construction": head,
        "catalogue_hash": ctx["catalogue_hash"],
        "catalogue_hash_matches_record": True,
        "registry_version": ctx["registry_version"],
        "adapter_mode": adapter_mode,
        "model": model,
        "representation": (
            "a reproducible representation of the "
            "evidenced iteration-1 request, regenerated "
            "by the real construction path (the loop's "
            "package construction over the record "
            "truncated at the activation event; the "
            "adapter's prompt rendering; the transport's "
            "request construction) and verified against "
            "the record's own LOOP_ITERATION commitments. "
            "The one field no artifact records — the "
            "package bounds' seconds_remaining, a live "
            "countdown at construction — stands as the "
            "full pinned deadline, the value at the "
            "activation instant, the doorway's clock "
            "standing at the stored activation anchor "
            "while the real derivation ran."),
        "seconds_remaining_in_package":
            package["bounds"]["seconds_remaining"],
    }
    return request, package, info


